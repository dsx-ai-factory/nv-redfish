#[cfg(feature = "task-service")]
use crate::schema::message::Message;
#[cfg(feature = "task-service")]
use crate::schema::task::TaskState;
use nv_redfish_core::Bmc;
use nv_redfish_quirks::CompatError;
use nv_redfish_quirks::DecodeError;
use serde_json::Error as JsonError;
use std::error::Error as StdError;
use std::fmt::Debug;
use std::fmt::Display;
use std::fmt::Formatter;
use std::fmt::Result as FmtResult;

/// Redfish Errors.
pub enum Error<B: Bmc> {
    /// Errors generated by BMC access.
    Bmc(B::Error),
    /// No available preallocated account slot was found.
    #[cfg(feature = "accounts")]
    AccountSlotNotAvailable,
    /// Action not available for this resource
    ActionNotAvailable,
    /// Event service does not provide `ServerSentEventUri`
    #[cfg(feature = "event-service")]
    EventServiceServerSentEventUriNotAvailable,
    /// Update service does not provide `MultipartHttpPushUri`
    #[cfg(feature = "update-service")]
    UpdateServiceMultipartHttpPushUriNotAvailable,
    /// Update service does not provide `HttpPushUri`
    #[cfg(feature = "update-service-deprecated")]
    UpdateServiceHttpPushUriNotAvailable,
    /// Task service does not provide a Tasks collection.
    #[cfg(feature = "task-service")]
    TaskServiceTasksUnavailable,
    /// Task location does not point at this TaskService Tasks collection.
    #[cfg(feature = "task-service")]
    TaskLocationNotInTaskService {
        /// Task location.
        task_location: nv_redfish_core::ODataId,
        /// Expected TaskService Tasks collection path.
        task_collection: nv_redfish_core::ODataId,
    },
    /// An asynchronous operation completed without exposing its typed result.
    #[cfg(feature = "task-service")]
    TaskResultUnavailable,
    /// The Task of an asynchronous operation ended without completing.
    #[cfg(feature = "task-service")]
    TaskFailed {
        /// Terminal state: `Exception`, `Killed`, or `Cancelled`.
        state: TaskState,
        /// Messages the Task recorded.
        messages: Vec<Message>,
    },
    /// An asynchronous operation was polled after an earlier poll returned
    /// its outcome.
    #[cfg(feature = "task-service")]
    TaskAlreadyFinished,
    /// Job location does not point at this Jobs collection.
    #[cfg(feature = "job-service")]
    JobLocationNotInJobs {
        /// Job location.
        job_location: nv_redfish_core::ODataId,
        /// Expected Jobs collection path.
        job_collection: nv_redfish_core::ODataId,
    },
    /// Metric definitions are not available for telemetry service
    #[cfg(feature = "telemetry-service")]
    MetricDefinitionsNotAvailable,
    /// Metric report definitions are not available for telemetry service
    #[cfg(feature = "telemetry-service")]
    MetricReportDefinitionsNotAvailable,
    /// JSON parse error.
    Json(JsonError),
    /// A document did not deserialize into the schema type it was read as:
    /// a resource after its repairs, or the reply to a write as it came.
    /// The error names the path to the property that failed.
    Decode(DecodeError),
}

impl<B: Bmc> Display for Error<B> {
    #[allow(clippy::too_many_lines)]
    fn fmt(&self, f: &mut Formatter<'_>) -> FmtResult {
        match self {
            Self::Bmc(err) => write!(f, "BMC error: {err}"),
            Self::Json(err) => write!(f, "JSON error: {err}"),
            Self::Decode(err) => write!(f, "Decode error: {err}"),
            #[cfg(feature = "accounts")]
            Self::AccountSlotNotAvailable => {
                write!(f, "Free account slot is not found")
            }
            Self::ActionNotAvailable => {
                write!(f, "Action is not available for this resource")
            }
            #[cfg(feature = "event-service")]
            Self::EventServiceServerSentEventUriNotAvailable => {
                write!(f, "Event service does not provide ServerSentEventUri")
            }
            #[cfg(feature = "update-service")]
            Self::UpdateServiceMultipartHttpPushUriNotAvailable => {
                write!(f, "Update service does not provide MultipartHttpPushUri")
            }
            #[cfg(feature = "update-service-deprecated")]
            Self::UpdateServiceHttpPushUriNotAvailable => {
                write!(f, "Update service does not provide HttpPushUri")
            }
            #[cfg(feature = "task-service")]
            Self::TaskServiceTasksUnavailable => {
                write!(f, "Task service does not provide Tasks collection")
            }
            #[cfg(feature = "task-service")]
            Self::TaskLocationNotInTaskService {
                task_location,
                task_collection,
            } => write!(
                f,
                "Task location {task_location} is not in TaskService Tasks collection {task_collection}"
            ),
            #[cfg(feature = "job-service")]
            Self::JobLocationNotInJobs {
                job_location,
                job_collection,
            } => write!(
                f,
                "Job location {job_location} is not in Jobs collection {job_collection}"
            ),
            #[cfg(feature = "task-service")]
            Self::TaskResultUnavailable => {
                write!(f, "Task completed without exposing its result")
            }
            #[cfg(feature = "task-service")]
            Self::TaskFailed { state, messages } => {
                write!(f, "Task ended in state {state:?}")?;
                for message in messages {
                    let text = message.message.as_deref().unwrap_or(&message.message_id);
                    write!(f, "; {text}")?;
                }
                Ok(())
            }
            #[cfg(feature = "task-service")]
            Self::TaskAlreadyFinished => {
                write!(f, "Task outcome was already returned by an earlier poll")
            }
            #[cfg(feature = "telemetry-service")]
            Self::MetricDefinitionsNotAvailable => {
                write!(f, "Metric definitions are not available")
            }
            #[cfg(feature = "telemetry-service")]
            Self::MetricReportDefinitionsNotAvailable => {
                write!(f, "Metric report definitions are not available")
            }
        }
    }
}

impl<B: Bmc> Debug for Error<B> {
    fn fmt(&self, f: &mut Formatter<'_>) -> FmtResult {
        Display::fmt(self, f)
    }
}

impl<B: Bmc> StdError for Error<B> {}

/// Requests go through the compatibility layer: its transport failures are
/// the BMC's own, and a document that did not deserialize is a decode
/// error.
impl<B: Bmc> From<CompatError<B::Error>> for Error<B> {
    fn from(err: CompatError<B::Error>) -> Self {
        match err {
            CompatError::Transport(err) => Self::Bmc(err),
            CompatError::Decode(err) => Self::Decode(err),
        }
    }
}
