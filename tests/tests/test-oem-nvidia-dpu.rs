// BlueField-3 ComputerSystem OEM actions.

// These calls compile against the actual OEM CSDL generated by redfish/build.rs.
// Compiling this test checks that both Set actions coexist with distinct methods.
#[test]
async fn generated_dpu_actions_are_callable() -> Result<(), Box<dyn StdError>> {
    let bmc = Arc::new(Bmc::default());
    let system = bf3_system(bmc.clone()).await?;
    let oem = bf3_oem(&bmc, &system).await?;
    let raw = oem.raw();
    let actions = raw.actions.as_ref().expect("DPU actions are advertised");

    bmc.expect(Expect::action(
        format!("{BF3_OEM}/Actions/Mode.Set"),
        json!({"Mode": "NicMode"}),
        json!(null),
    ));
    assert!(matches!(
        actions.mode_set(bmc.as_ref(), Mode::NicMode).await?,
        ModificationResponse::Entity(())
    ));

    bmc.expect(Expect::action(
        format!("{BF3_OEM}/Actions/HostRshim.Set"),
        json!({"HostRshim": "Enabled"}),
        json!(null),
    ));
    assert!(matches!(
        actions
            .host_rshim_set(bmc.as_ref(), HostRshim::Enabled)
            .await?,
        ModificationResponse::Entity(())
    ));

    bmc.expect(Expect::action(
        format!("{BF3_OEM}/SOC.ForceReset"),
        json!({}),
        json!(null),
    ));
    assert!(matches!(
        actions.force_reset(bmc.as_ref()).await?,
        ModificationResponse::Entity(())
    ));
    Ok(())
}

